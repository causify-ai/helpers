def _process_row(
    row: Dict[str, Any],
    *,
    script: str,
    output_dir: str,
    model: str,
    no_incremental: bool,
    dry_run: bool,
) -> Tuple[str, Optional[Dict[str, Any]]]:
    """
    Download, summarize, and save the merged summary for a single row.

    Destination-agnostic: only writes the merged summary and stats under
    `output_dir` and sets `Done`; copying to a destination is handled
    separately by `_reconcile_destination()`, so the same cached file can
    later be backfilled into a different destination without re-processing.

    :param row: CSV row dict; mutated in place (`Done` is set to `"yes"` on
        success, or to `"skipped"` for a row that can never be processed)
    :param script: path to `download_hn_article_to_md.py`
    :param output_dir: local dir for the raw per-item files and the merged
        summary
    :param model: LLM model passed through to `download_hn_article_to_md.py`
        for both summarization phases; `""` uses that script's own default
    :param no_incremental: if True, force `download_hn_article_to_md.py` to
        overwrite existing local per-item files
    :param dry_run: if True, log what would be done without doing it
    :return: a tuple
        - status: `"processed"` (`Done` set to `"yes"`), `"skipped"` (`Done`
          set to `"skipped"`; `Hn_url` isn't a real HN item URL, so the row
          can never be processed by this script), `"dry_run"` (`--dry_run`,
          row otherwise valid), or `"failed"` (download/summarize error;
          `Done` left unset so the row is retried next run)
        - the full contents of the saved `*.stats.json` file (read back from
          disk), or None unless status is `"processed"`
    """
    _LOG.debug(
        hprint.to_str("output_dir model no_incremental dry_run")
    )
    hn_url = (row.get("Hn_url") or "").strip()
    if not hn_url or not dshdbout.is_hackernews_url(hn_url):
        _LOG.warning(
            "Skipping row with invalid Hn_url (not a Hacker News item "
            "URL): '%s'",
            hn_url,
        )
        if not dry_run:
            # Permanently skip: this row can never be processed by this
            # script (e.g., a plain article link Raindrop.io put in the
            # Hn_url column), so stop it from occupying --limit slots on
            # every future run. Handling plain-article bookmarks is
            # explicitly out of scope.
            row["Done"] = "skipped"
        return "skipped", None
    item_id = dshdbout.extract_item_id(hn_url)
    title = (row.get("Title") or "").strip()
    if dry_run:
        _LOG.info(
            "[DRY_RUN] Processing item %s: '%s', '%s'",
            item_id,
            hn_url,
            title,
        )
        _LOG.debug(
            "[DRY RUN] Would download+summarize '%s' into '%s' and set "
            "Done=yes",
            hn_url,
            output_dir,
        )
        return "dry_run", None
    _LOG.info(
        "Processing item %s: '%s', '%s'",
        item_id,
        hn_url,
        title,
    )
    # Download and summarize the submission (article + HN comments).
    cmd_parts = [
        script,
        f'--input "{hn_url}"',
        f'--output_dir "{output_dir}"',
    ]
    if model:
        cmd_parts.append(f'--model "{model}"')
    if no_incremental:
        cmd_parts.append("--no_incremental")
    cmd = " ".join(cmd_parts)
    download_start_time = time.time()
    hsystem.system(cmd, print_command=True)
    total_wallclock_time_in_seconds = time.time() - download_start_time
    # Locate the generated summary files: `download_hn_article_to_md.py` owns
    # the exact `<date>.hn_<item_id>.<title>` naming, so glob for it by
    # `item_id` instead of re-deriving the title slug/date here.
    hn_matches = sorted(
        glob.glob(
            os.path.join(output_dir, f"*.hn_{item_id}.*{_HN_SUMMARY_SUFFIX}")
        )
    )
    if not hn_matches:
        _LOG.warning(
            "No HN comments summary generated for item %s, skipping", item_id
        )
        return "failed", None
    hn_summary_file = hn_matches[-1]
    article_matches = sorted(
        glob.glob(
            os.path.join(
                output_dir, f"*.hn_{item_id}.*{_ARTICLE_SUMMARY_SUFFIX}"
            )
        )
    )
    article_summary_file = article_matches[-1] if article_matches else None
    merged_filename, merged_content = _build_merged_summary(
        row, hn_summary_file, article_summary_file
    )
    local_merged_file = os.path.join(output_dir, merged_filename)
    hio.to_file(local_merged_file, merged_content)
    # Save the per-row stats (download wallclock time + both summarization
    # phases' LLM stats) locally, next to the merged summary.
    stats_filename, stats, row_cost_in_dollars = _build_stats(
        merged_filename,
        total_wallclock_time_in_seconds,
        hn_summary_file,
        article_summary_file,
    )
    local_stats_file = os.path.join(output_dir, stats_filename)
    hio.to_json(local_stats_file, stats)
    # Read back the stats file (instead of reusing the in-memory `stats`
    # dict) so the caller gets exactly what was persisted to disk, and
    # decides what to do with it (e.g., extract the cost, log fields).
    row_stats = hio.from_json(local_stats_file)
    _LOG.info(
        "Saved stats to '%s' (cost: $%.6f)",
        local_stats_file,
        row_cost_in_dollars,
    )
    _LOG.info(
        "Saved merged summary to '%s' (destination copy handled by "
        "reconciliation)",
        local_merged_file,
    )
    row["Done"] = "yes"
    return "processed", row_stats


