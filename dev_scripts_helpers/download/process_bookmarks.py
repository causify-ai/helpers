def _find_cached_merged_summary(
    output_dir: str, item_id: str
) -> Optional[str]:
    """
    Find the cached `<base>.summary.md` merged-summary file for `item_id`
    under `output_dir`, if `_process_row()` already produced it.

    Globbing for `*.summary.md` also matches the 2 raw per-item summary
    files (`*.2.article_url.summary.md` / `*.4.hn_url.summary.md`), since
    both suffixes end in `.summary.md` too; those are excluded since they
    are merge inputs, not the merge output.

    :param output_dir: local dir holding cached per-item and merged files
    :param item_id: HN item ID (as extracted from `Hn_url`)
    :return: path to the merged summary file, or None if not cached
    """
    candidates = sorted(
        glob.glob(os.path.join(output_dir, f"*.hn_{item_id}.*.summary.md"))
    )
    merged_candidates = [
        c
        for c in candidates
        if not c.endswith(_ARTICLE_SUMMARY_SUFFIX)
        and not c.endswith(_HN_SUMMARY_SUFFIX)
    ]
    if not merged_candidates:
        return None
    return merged_candidates[-1]


def _reconcile_destination(
    rows: List[Dict[str, Any]],
    *,
    output_dir: str,
    dest_dir: Optional[str],
    dry_run: bool,
) -> List[str]:
    """
    Copy the cached merged summary for every `Done=yes` row whose file is
    missing from `dest_dir`.

    Runs over *all* `Done=yes` rows, not bounded by `--limit`: this is what
    makes destinations independent -- running once with one `--dest_type`
    and later with another backfills the new one for free from rows
    already processed, with no re-download, no re-summarize, no LLM cost.

    :param rows: all CSV rows
    :param output_dir: local dir holding the cached `<base>.summary.md`
        files written by `_process_row()`
    :param dest_dir: destination dir to reconcile into, or None for
        `--dest_type none` (nothing to reconcile)
    :param dry_run: if True, only report what would be copied, without
        touching the filesystem
    :return: merged filenames copied (or, in `dry_run`, that would be
        copied)
    """
    _LOG.debug(hprint.to_str("output_dir dest_dir dry_run"))
    if dest_dir is None:
        return []
    done_rows = [r for r in rows if (r.get("Done") or "").strip() == "yes"]
    copied_filenames = []
    for row in done_rows:
        hn_url = (row.get("Hn_url") or "").strip()
        if not hn_url or not dshdbout.is_hackernews_url(hn_url):
            # Shouldn't happen for a Done=yes row, but guard defensively
            # since item_id extraction below requires a real HN item URL.
            continue
        item_id = dshdbout.extract_item_id(hn_url)
        merged_file = _find_cached_merged_summary(output_dir, item_id)
        if merged_file is None:
            _LOG.warning(
                "Done=yes row for item %s has no cached merged summary "
                "under '%s'; skipping reconciliation for it",
                item_id,
                output_dir,
            )
            continue
        merged_filename = os.path.basename(merged_file)
        dest_file = os.path.join(dest_dir, merged_filename)
        if os.path.exists(dest_file):
            continue
        if dry_run:
            _LOG.info(
                "[DRY_RUN] Would copy '%s' -> '%s'", merged_file, dest_file
            )
        else:
            shutil.copy2(merged_file, dest_file)
            _LOG.info("Copied '%s' -> '%s'", merged_file, dest_file)
        copied_filenames.append(merged_filename)
    return copied_filenames


