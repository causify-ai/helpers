def _resolve_dest_dir(dest_type: str, dest_dir: str) -> Optional[str]:
    """
    Resolve the destination dir for the selected `--dest_type`.

    :param dest_type: `"gdrive"`, `"obsidian"`, or `"none"`
    :param dest_dir: `--dest_dir` override, or `""` to use the built-in
        default path for `dest_type`
    :return: absolute path to the destination dir, or `None` for
        `dest_type="none"` (nothing to copy to)
    """
    _LOG.debug(hprint.to_str("dest_type dest_dir"))
    if dest_type == "none":
        return None
    if dest_dir:
        return dest_dir
    default_dir_by_type = {
        "gdrive": _DEFAULT_GDRIVE_DIR,
        "obsidian": _DEFAULT_OBSIDIAN_DIR,
    }
    hdbg.dassert_in(dest_type, default_dir_by_type, "Invalid --dest_type")
    return default_dir_by_type[dest_type]


