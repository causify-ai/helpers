r"""
Process unprocessed bookmarks from a CSV file: download and summarize each
Hacker News submission, save a merged summary to a destination, and mark
the row as done.

For each row without the `Done` flag set (up to `--limit` rows), this:

1) Downloads and summarizes the submission via `download_hn_article_to_md.py`
   (article + HN comments, saved under `--output_dir`)
2) Merges the article summary and HN comments summary into a single
   `<date>.hn_<item_id>.<title>.summary.md` file, prefixed with a backlink
   header (`Article: <url>` / `HN: <url>`)
3) Saves a `<date>.hn_<item_id>.<title>.stats.json` file under
   `--output_dir` with the wallclock time spent downloading and the LLM
   usage stats (model, char counts, wallclock time, cost) for both
   summarization phases
4) Sets `Done=yes` for that row and saves the CSV in place

A row whose `Hn_url` isn't a real HN item URL (`news.ycombinator.com/
item?id=...`) is set to `Done=skipped` immediately instead, with no
download.

Separately, every invocation also runs a **destination reconciliation
pass** over *all* `Done=yes` rows (not bounded by `--limit`): for the
`--dest_type`/`--dest_dir` selected this run, any row whose cached merged
summary (under `--output_dir`) is missing from the destination gets copied
there -- no re-download, no re-summarize, no LLM cost. This is what makes
`--dest_type gdrive` and `--dest_type obsidian` independent: switching to a
new destination later backfills it for free from rows already processed.
`--limit 0` runs reconciliation only (no new rows processed).

The cost of each row's 2 summarization phases (article + HN comments) is
summed into a running total, shown in the progress bar and logged at the
end as the total summarization cost for the run.

# Usage Example

- Process up to 10 unprocessed rows (default), copying to Google Drive:
> process_bookmarks.py \
    --input /Users/saggese/src/notes1/bookmarks/update_gsheet_links_from_raindrop.combined_data.csv \
    --limit 10

- Preview what would be done without downloading/writing anything:
> process_bookmarks.py --input bookmarks.csv --dry_run

- Reprocess rows even if already marked `Done`, overwriting existing local
  output files:
> process_bookmarks.py --input bookmarks.csv --no_incremental

- Copy merged summaries to the Obsidian vault instead of Google Drive:
> process_bookmarks.py --input bookmarks.csv --dest_type obsidian

- Keep the merged summaries local (under `--output_dir`) only:
> process_bookmarks.py --input bookmarks.csv -o ./tmp.hn_downloads \
    --dest_type none

- Backfill a destination for rows already processed, without downloading
  anything new:
> process_bookmarks.py --input bookmarks.csv --dest_type obsidian --limit 0

Import as:

import dev_scripts_helpers.download.process_bookmarks as dshdprbo
"""

