def _main(parser: argparse.ArgumentParser) -> None:
    """
    Main entry point.
    """
    _LOG.debug(hprint.func_signature_to_str())
    args = parser.parse_args()
    hdbg.init_logger(verbosity=args.log_level, use_exec_path=True)
    rows = dshdbout.read_csv(args.input)
    hdbg.dassert(rows, "No rows in CSV: %s", args.input)
    columns = list(rows[0].keys())
    hdbg.dassert_in("Hn_url", columns, "CSV must have 'Hn_url' column")
    hdbg.dassert_in("Done", columns, "CSV must have 'Done' column")
    dest_dir = _resolve_dest_dir(args.dest_type, args.dest_dir)
    selected_rows = _select_rows(
        rows, no_incremental=args.no_incremental, limit=args.limit
    )
    if args.dry_run:
        _LOG.warning("DRY RUN MODE: showing what would be done without executing")
    script = hgit.find_file_in_git_tree("download_hn_article_to_md.py")
    if not args.dry_run:
        hio.create_dir(args.output_dir, incremental=True)
        if dest_dir is not None:
            hio.create_dir(dest_dir, incremental=True)
    # Row processing: bounded by --limit, downloads/summarizes/merges new
    # (not-yet-Done) rows.
    num_processed = 0
    num_skipped = 0
    num_would_process = 0
    total_cost_in_dollars = 0.0
    progress_bar = tqdm(selected_rows, desc="Processing bookmarks")
    for row in progress_bar:
        status, row_stats = _process_row(
            row,
            script=script,
            output_dir=args.output_dir,
            model=args.model,
            no_incremental=args.no_incremental,
            dry_run=args.dry_run,
        )
        if status == "processed":
            num_processed += 1
            if row_stats is not None:
                # `row_stats` is the stats.json content; pull out the cost.
                total_cost_in_dollars += row_stats.get(
                    "total_cost_in_dollars", 0.0
                )
                progress_bar.set_postfix_str(
                    f"Cost: ${total_cost_in_dollars:.4f}"
                )
        elif status == "skipped":
            num_skipped += 1
        elif status == "dry_run":
            num_would_process += 1
        if status in ("processed", "skipped") and not args.dry_run:
            # Persist after each row (processed or newly skipped) so an
            # interrupted run can resume without redoing work.
            dshdbout.write_csv(args.input, rows, fieldnames=columns)
    if args.dry_run:
        # `_process_row()` never returns "processed" in dry_run mode (it
        # short-circuits to "dry_run" for otherwise-valid rows), so report
        # what *would* happen using distinct wording.
        _LOG.info(
            "[DRY_RUN] Would process %d/%d selected row(s), would skip %d "
            "(limit=%d)",
            num_would_process,
            len(selected_rows),
            num_skipped,
            args.limit,
        )
    else:
        _LOG.info(
            "Processed %d/%d selected row(s), skipped %d (limit=%d)",
            num_processed,
            len(selected_rows),
            num_skipped,
            args.limit,
        )
    _LOG.info(
        "Total summarization cost for this run: $%.6f", total_cost_in_dollars
    )
    # Destination reconciliation: runs over ALL Done=yes rows every
    # invocation, not bounded by --limit (--limit 0 runs this only).
    copied_filenames = _reconcile_destination(
        rows, output_dir=args.output_dir, dest_dir=dest_dir, dry_run=args.dry_run
    )
    if dest_dir is None:
        _LOG.info("Destination reconciliation skipped (--dest_type none)")
    elif args.dry_run:
        _LOG.info(
            "[DRY_RUN] Would copy/repair %d row(s) into destination '%s'",
            len(copied_filenames),
            dest_dir,
        )
    else:
        _LOG.info(
            "Reconciled %d row(s) into destination '%s'",
            len(copied_filenames),
            dest_dir,
        )


if __name__ == "__main__":
    _main(_parse())
